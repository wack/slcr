//! The canonical Markdown rendering of a specification, per section 8 of the
//! SLCR design document: one deterministic document per specification that
//! reads top to bottom.
//!
//! The same graph always renders to the same bytes. Headings follow the
//! containment tree, siblings keep their serialized order, and the Glossary
//! comes last, alphabetized. IDs never appear in the visible text; each node
//! is preceded by a hidden anchor carrying its ID, which cross-references
//! link to.

use std::collections::HashMap;
use std::fmt::{self, Display};

use blocks::Blocks;
use inline::{anchor, escape, escape_html, link};

use crate::spec::check;
use crate::spec::graph::SlcrRequirementsDocument;
use crate::spec::id::{DependencyId, RequirementId, SectionId, TermId};
use crate::spec::node::{Refinement, Requirement, Section, SectionChild, Term};
use crate::spec::text::Title;

mod blocks;
mod inline;

/// How every rendered document begins, so that a file that begins any other
/// way is known not to have been rendered.
const GENERATED_PREFIX: &str = "<!-- Generated by slcr ";

/// The deepest heading Markdown has. Deeper nodes render as bold numbered
/// paragraphs instead.
const DEEPEST_HEADING: usize = 6;

/// Render `graph` as Markdown.
pub(crate) fn document(graph: &SlcrRequirementsDocument) -> String {
    Renderer::new(graph).render()
}

/// Whether `contents` begins as a rendered document does, which marks a file
/// that may be replaced by rendering again.
pub(crate) fn is_rendered(contents: &[u8]) -> bool {
    contents.starts_with(GENERATED_PREFIX.as_bytes())
}

/// The position of a node in the containment tree: empty for the root, and
/// otherwise each ancestor's 1-based position among its siblings, ending
/// with the node's own.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
struct Number(Vec<usize>);

impl Number {
    /// The number of this node's `position`th child, counting from 1.
    fn child(&self, position: usize) -> Self {
        let mut parts = self.0.clone();
        parts.push(position);
        Self(parts)
    }

    /// How far below the root the node is.
    fn depth(&self) -> usize {
        self.0.len()
    }
}

impl Display for Number {
    /// `2.` at the top level, then `2.1`, `2.1.3`, and so on.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let parts: Vec<String> = self.0.iter().map(ToString::to_string).collect();
        f.write_str(&parts.join("."))?;
        if parts.len() == 1 {
            f.write_str(".")?;
        }
        Ok(())
    }
}

/// Renders one document, with the lookups that cross-references need.
struct Renderer<'a> {
    graph: &'a SlcrRequirementsDocument,
    /// Every Section's title, the Glossary's included.
    sections: HashMap<SectionId, &'a Title>,
    requirements: HashMap<RequirementId, &'a Requirement>,
    terms: HashMap<TermId, &'a Term>,
    /// The requirements that refine each requirement, in document order.
    refiners: HashMap<RequirementId, Vec<&'a Requirement>>,
    blocks: Blocks,
}

impl<'a> Renderer<'a> {
    fn new(graph: &'a SlcrRequirementsDocument) -> Self {
        let glossary = graph.glossary();
        let sections = graph
            .sections()
            .into_iter()
            .map(|section| (*section.id(), section.title()))
            .chain([(*glossary.id(), glossary.title())])
            .collect();
        let requirements = graph.requirements();
        let refiners = check::refiners(&requirements);
        let requirements = requirements
            .into_iter()
            .map(|requirement| (*requirement.id(), requirement))
            .collect();
        let terms = glossary
            .terms()
            .iter()
            .map(|term| (*term.id(), term))
            .collect();
        Self {
            graph,
            sections,
            requirements,
            terms,
            refiners,
            blocks: Blocks::new(),
        }
    }

    fn render(mut self) -> String {
        self.blocks.push(&format!(
            "{GENERATED_PREFIX}from the {} specification. Do not edit: change the \
             specification and run `slcr render`. -->",
            self.graph.spec().name()
        ));
        let root = self.graph.root();
        self.section(root, &Number::default());
        // The Glossary is logically the root's last child.
        self.glossary(&Number::default().child(root.children().len() + 1));
        self.blocks.finish()
    }

    /// The hidden anchor and the numbered heading of a node, or a bold
    /// numbered paragraph below the deepest heading.
    fn heading(&mut self, id: impl Display, number: &Number, title: &Title) {
        let title = escape(title.as_str());
        let text = if number.depth() == 0 {
            title
        } else {
            format!("{number} {title}")
        };
        let level = number.depth() + 1;
        let heading = if level <= DEEPEST_HEADING {
            format!("{} {text}", "#".repeat(level))
        } else {
            format!("**{text}**")
        };
        self.blocks.push(&format!("{}\n{heading}", anchor(id)));
    }

    fn section(&mut self, section: &'a Section, number: &Number) {
        self.heading(section.id(), number, section.title());
        if let Some(body) = section.body() {
            self.blocks.prose(body);
        }
        self.terms_line(section.uses_term());
        for (index, child) in section.children().iter().enumerate() {
            let number = number.child(index + 1);
            match child {
                SectionChild::Section(child) => self.section(child, &number),
                SectionChild::Requirement(child) => self.requirement(child, &number, None),
            }
        }
    }

    /// Render `requirement`, whose containment parent is the requirement
    /// `parent`, or a Section if `None`.
    fn requirement(
        &mut self,
        requirement: &'a Requirement,
        number: &Number,
        parent: Option<RequirementId>,
    ) {
        let id = *requirement.id();
        self.heading(id, number, requirement.title());
        self.blocks.prose(requirement.body());
        if let Some(rationale) = requirement.rationale() {
            self.labeled("Rationale", rationale.as_str());
        }
        self.refinement(requirement);

        // The containment parent is plain from the document's structure.
        let refines: Vec<String> = requirement
            .refines()
            .iter()
            .filter(|target| Some(**target) != parent)
            .map(|target| self.requirement_link(*target))
            .collect();
        self.labeled("Refines", &refines.join(", "));

        let depends_on: Vec<String> = requirement
            .depends_on()
            .iter()
            .map(|target| self.dependency_link(*target))
            .collect();
        self.labeled("Depends on", &depends_on.join(", "));

        self.terms_line(requirement.uses_term());

        let criteria = requirement.acceptance_criteria();
        if !criteria.is_empty() {
            self.blocks.push("*Acceptance criteria:*");
            for criterion in criteria {
                self.blocks.push(&format!(
                    "{}**{}**",
                    anchor(criterion.id()),
                    escape(criterion.title().as_str())
                ));
                self.blocks.prose(criterion.body());
            }
        }

        for (index, child) in requirement.children().iter().enumerate() {
            self.requirement(child, &number.child(index + 1), Some(id));
        }
    }

    /// The refinement sentence, listing every requirement that refines
    /// `requirement`, wherever it is housed, in document order.
    fn refinement(&mut self, requirement: &Requirement) {
        let Some(refinement) = requirement.refinement() else {
            return;
        };
        let Some(refiners) = self.refiners.get(requirement.id()) else {
            return;
        };
        let sentence = match refinement {
            Refinement::And => "All of the following must hold:",
            Refinement::Or => "At least one of the following must hold:",
            Refinement::Xor => "Exactly one of the following must hold:",
        };
        let items: Vec<String> = refiners
            .iter()
            .map(|refiner| format!("- {}", link(refiner.title(), refiner.id())))
            .collect();
        self.blocks.push(sentence);
        self.blocks.push(&items.join("\n"));
    }

    fn terms_line(&mut self, terms: &[TermId]) {
        let links: Vec<String> = terms.iter().map(|term| self.term_link(*term)).collect();
        self.labeled("Terms", &links.join(", "));
    }

    /// A paragraph of `text` after an italic `label`, unless `text` is
    /// empty.
    fn labeled(&mut self, label: &str, text: &str) {
        let text = blocks::normalize(text);
        if !text.is_empty() {
            self.blocks.push(&format!("*{label}:* {text}"));
        }
    }

    fn glossary(&mut self, number: &Number) {
        let glossary = self.graph.glossary();
        self.heading(glossary.id(), number, glossary.title());
        if let Some(body) = glossary.body() {
            self.blocks.prose(body);
        }
        let mut terms: Vec<&Term> = glossary.terms().iter().collect();
        terms.sort_by_cached_key(|term| {
            let title = term.title().as_str();
            (title.to_lowercase(), title.to_owned(), *term.id())
        });

        if terms.is_empty() {
            return;
        }

        // CommonMark has no definition list, so the Glossary is an HTML one
        // whose definitions are Markdown, set off by blank lines.
        for (index, term) in terms.into_iter().enumerate() {
            // Each term's tags close the previous term's definition.
            let opening = if index == 0 { "<dl>" } else { "</dd>" };
            self.blocks.push(&format!(
                "{opening}\n<dt>{}{}</dt>\n<dd>",
                anchor(term.id()),
                escape_html(term.title().as_str())
            ));
            let aliases: Vec<String> = term
                .aliases()
                .iter()
                .map(|alias| escape(alias.as_str()))
                .collect();
            self.labeled("Also called", &aliases.join(", "));
            self.blocks.prose(term.definition());
        }
        self.blocks.push("</dd>\n</dl>");
    }

    /// A link to the requirement `id`, or its bare ID if no such
    /// requirement exists, which only an unchecked document allows.
    fn requirement_link(&self, id: RequirementId) -> String {
        self.requirements.get(&id).map_or_else(
            || id.to_string(),
            |requirement| link(requirement.title(), id),
        )
    }

    fn dependency_link(&self, id: DependencyId) -> String {
        match id {
            DependencyId::Requirement(id) => self.requirement_link(id),
            DependencyId::Section(id) => self
                .sections
                .get(&id)
                .map_or_else(|| id.to_string(), |title| link(title, id)),
        }
    }

    fn term_link(&self, id: TermId) -> String {
        self.terms
            .get(&id)
            .map_or_else(|| id.to_string(), |term| link(term.title(), id))
    }
}

