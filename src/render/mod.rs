    #[test]
    fn the_refines_line_omits_only_the_containment_parent() {
        let graph = spec(
            json!([
                with(
                    requirement(1, "Parent"),
                    json!({
                        "refinement": "AND",
                        "children": [
                            with(requirement(2, "Both"), json!({ "refines": ["REQ-003", "REQ-001"] })),
                            with(requirement(4, "Other only"), json!({ "refines": ["REQ-003"] })),
                            with(requirement(5, "Parent only"), json!({ "refines": ["REQ-001"] })),
                        ]
                    })
                ),
                with(requirement(3, "Other"), json!({ "refinement": "OR" })),
                with(
                    section(2, "Section"),
                    json!({ "children": [
                    with(requirement(6, "Under a section"), json!({ "refines": ["REQ-001"] })),
                ] })
                ),
            ]),
            json!([]),
        );
        let rendered = document(&graph);
        let refines_line = |title: &str| {
            let block = rendered.split(&format!(" {title}\n\n")).nth(1).unwrap();
            let next = block.find("\n\n<a id=").unwrap_or(block.len());
            block[..next]
                .lines()
                .find(|line| line.starts_with("*Refines:*"))
                .map(str::to_owned)
        };
        assert_eq!(
            refines_line("Both").as_deref(),
            Some("*Refines:* [Other](#REQ-003)")
        );
        assert_eq!(
            refines_line("Other only").as_deref(),
            Some("*Refines:* [Other](#REQ-003)")
        );
        assert_eq!(refines_line("Parent only"), None);
        assert_eq!(
            refines_line("Under a section").as_deref(),
            Some("*Refines:* [Parent](#REQ-001)")
        );
    }

