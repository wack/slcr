    /// A checked document whose root, SEC-001 "Root", contains `children`,
    /// and whose Glossary, SEC-900, holds `terms`.
    fn spec(children: Value, terms: Value) -> SlcrRequirementsDocument {
        serde_json::from_value(spec_value(children, terms)).unwrap()
    }

    fn spec_value(children: Value, terms: Value) -> Value {
        let mut root = json!({ "kind": "section", "id": "SEC-001", "title": "Root" });
        if children != json!([]) {
            root["children"] = children;
        }
        let mut glossary = json!({ "kind": "section", "id": "SEC-900", "title": "Glossary" });
        if terms != json!([]) {
            glossary["terms"] = terms;
        }
        json!({
            "formatVersion": "1",
            "spec": { "name": "todo-api" },
            "root": root,
            "glossary": glossary,
        })
    }

    fn section(id: u32, title: &str) -> Value {
        json!({ "kind": "section", "id": format!("SEC-{id:03}"), "title": title })
    }

    /// A leaf MUST requirement whose body states its modality.
    fn requirement(id: u32, title: &str) -> Value {
        json!({
            "kind": "requirement",
            "id": format!("REQ-{id:03}"),
            "title": title,
            "body": format!("{title} MUST hold."),
            "modality": "MUST",
        })
    }

    fn term(id: u32, title: &str, definition: &str) -> Value {
        json!({
            "kind": "term",
            "id": format!("TERM-{id:03}"),
            "title": title,
            "definition": definition,
        })
    }

    /// `node` with `fields` set.
    fn with(mut node: Value, fields: Value) -> Value {
        let node_fields = node.as_object_mut().unwrap();
        for (key, value) in fields.as_object().unwrap() {
            node_fields.insert(key.clone(), value.clone());
        }
        node
    }

    /// What renders between the root's heading and the Glossary's anchor,
    /// for a root without a body.
    fn middle(rendered: &str) -> &str {
        let start = rendered.find("# Root\n\n").expect("the root heading") + "# Root\n\n".len();
        let end = rendered
            .find(r#"<a id="SEC-900"></a>"#)
            .expect("the Glossary's anchor");
        rendered[start..end].trim_end()
    }

    fn parse(markdown: &str) -> Parser<'_> {
        Parser::new_ext(
            markdown,
            Options::ENABLE_STRIKETHROUGH | Options::ENABLE_TABLES,
        )
    }

    /// Each heading's level and text, in order.
    fn headings(markdown: &str) -> Vec<(usize, String)> {
        let mut headings = Vec::new();
        let mut current: Option<(usize, String)> = None;
        for event in parse(markdown) {
            match event {
                Event::Start(Tag::Heading { level, .. }) => {
                    current = Some((heading_level(level), String::new()));
                }
                Event::Text(text) | Event::Code(text) => {
                    if let Some((_, heading)) = &mut current {
                        heading.push_str(&text);
                    }
                }
                Event::End(pulldown_cmark::TagEnd::Heading(_)) => {
                    headings.extend(current.take());
                }
                _ => {}
            }
        }
        headings
    }

    fn heading_level(level: HeadingLevel) -> usize {
        match level {
            HeadingLevel::H1 => 1,
            HeadingLevel::H2 => 2,
            HeadingLevel::H3 => 3,
            HeadingLevel::H4 => 4,
            HeadingLevel::H5 => 5,
            HeadingLevel::H6 => 6,
        }
    }

    /// The IDs of the anchors in `markdown`'s raw HTML, in order.
    fn anchors(markdown: &str) -> Vec<String> {
        const OPEN: &str = r#"<a id=""#;
        let mut anchors = Vec::new();
        for event in parse(markdown) {
            let (Event::Html(html) | Event::InlineHtml(html)) = event else {
                continue;
            };
            let mut rest = &*html;
            while let Some(start) = rest.find(OPEN) {
                rest = &rest[start + OPEN.len()..];
                let end = rest.find('"').expect("a closing quote");
                anchors.push(rest[..end].to_owned());
                rest = &rest[end..];
            }
        }
        anchors
    }

    /// The destinations of `markdown`'s links, in order.
    fn link_targets(markdown: &str) -> Vec<String> {
        parse(markdown)
            .filter_map(|event| match event {
                Event::Start(Tag::Link { dest_url, .. }) => Some(dest_url.to_string()),
                _ => None,
            })
            .collect()
    }

    /// The text a reader sees, outside raw HTML.
    fn visible_text(markdown: &str) -> String {
        let texts: Vec<String> = parse(markdown)
            .filter_map(|event| match event {
                Event::Text(text) | Event::Code(text) => Some(text.to_string()),
                _ => None,
            })
            .collect();
        texts.join("\n")
    }

    /// The ID of every node in `graph`, the Glossary's included.
    fn node_ids(graph: &SlcrRequirementsDocument) -> Vec<String> {
        let requirements = graph.requirements();
        let sections = graph.sections().into_iter().map(|s| s.id().to_string());
        let glossary = [graph.glossary().id().to_string()];
        let reqs = requirements.iter().map(|r| r.id().to_string());
        let criteria = requirements
            .iter()
            .flat_map(|r| r.acceptance_criteria())
            .map(|c| c.id().to_string());
        let terms = graph.glossary().terms().iter().map(|t| t.id().to_string());
        let mut ids: Vec<String> = sections
            .chain(glossary)
            .chain(reqs)
            .chain(criteria)
            .chain(terms)
            .collect();
        ids.sort();
        ids
    }

    /// Assert what holds of every rendered document: one anchor for every
    /// node and no other, every link resolving to one, headings no deeper
    /// than H6, no ID in the visible text, and clean text.
    fn assert_well_formed(graph: &SlcrRequirementsDocument) {
        let rendered = document(graph);

        let anchors = anchors(&rendered);
        let unique: HashSet<&str> = anchors.iter().map(String::as_str).collect();
        assert_eq!(unique.len(), anchors.len(), "anchors repeat");
        let mut sorted = anchors.clone();
        sorted.sort();
        assert_eq!(sorted, node_ids(graph));

        for target in link_targets(&rendered) {
            let id = target.strip_prefix('#').expect("an intra-document link");
            assert!(unique.contains(id), "{target} resolves to nothing");
        }

        let headings = headings(&rendered);
        assert!(headings.iter().all(|(level, _)| *level <= DEEPEST_HEADING));
        assert_eq!(headings[0], (1, graph.root().title().to_string()));

        let text = visible_text(&rendered);
        for prefix in ["SEC-", "REQ-", "TERM-", "AC-"] {
            assert!(!text.contains(prefix), "an ID is visible: {text}");
        }

        assert!(!rendered.contains('\r'));
        assert!(rendered.ends_with('\n') && !rendered.ends_with("\n\n"));
        assert!(is_rendered(rendered.as_bytes()));
    }

    /// A larger document using every construct: Sections nested two deep,
    /// three chains of requirements each nested seven deep, below the
    /// deepest heading, where each refines its container; refinements and
    /// dependencies across chains; terms with aliases; and criteria.
    fn synthetic() -> SlcrRequirementsDocument {
        const CHAINS: u32 = 3;
        const LENGTH: u32 = 7;
        let id = |chain: u32, level: u32| chain * LENGTH + level + 1;
        let mut criteria = 0;
        let mut top_sections = Vec::new();
        for chain in 0..CHAINS {
            let mut node: Option<Value> = None;
            for level in (0..LENGTH).rev() {
                let mut requirement =
                    requirement(id(chain, level), &format!("Chain {chain} level {level}"));
                let mut refines = Vec::new();
                if level > 0 {
                    refines.push(json!(format!("REQ-{:03}", id(chain, level - 1))));
                }
                if level + 1 < LENGTH {
                    requirement["refinement"] = json!("AND");
                }
                if level + 1 == LENGTH && chain > 0 {
                    refines.push(json!(format!("REQ-{:03}", id(chain - 1, 0))));
                }
                if level == 0 && chain + 1 < CHAINS {
                    // The next chain's deepest requirement refines this one.
                    requirement["refinement"] = json!("AND");
                }
                if !refines.is_empty() {
                    requirement["refines"] = json!(refines);
                }
                if level == 3 && chain > 0 {
                    requirement["dependsOn"] = json!([
                        format!("SEC-{:03}", chain + 1),
                        format!("REQ-{:03}", id(chain - 1, 2)),
                    ]);
                }
                if level == 1 {
                    requirement["usesTerm"] = json!([format!("TERM-{:03}", chain + 1)]);
                }
                if level == 2 {
                    let mut list = Vec::new();
                    for title in ["First criterion", "Second criterion"] {
                        criteria += 1;
                        list.push(json!({
                            "kind": "acceptanceCriterion",
                            "id": format!("AC-{criteria:03}"),
                            "title": title,
                            "body": "Done looks like this.\n\n```text\nsketch\n```",
                        }));
                    }
                    requirement["acceptanceCriteria"] = json!(list);
                }
                if let Some(child) = node.take() {
                    requirement["children"] = json!([child]);
                }
                node = Some(requirement);
            }
            let inner = with(
                section(chain + 5, &format!("Chain {chain} details")),
                json!({ "body": "Background.", "children": [node.unwrap()] }),
            );
            top_sections.push(with(
                section(chain + 2, &format!("Chain {chain}")),
                json!({ "usesTerm": [format!("TERM-{:03}", chain + 1)], "children": [inner] }),
            ));
        }
        let terms = json!([
            with(
                term(1, "zeta", "The last letter."),
                json!({ "aliases": ["Z"] })
            ),
            term(2, "Alpha", "The first letter.\n\nIt comes first."),
            term(3, "beta", "The second letter."),
        ]);
        spec(json!(top_sections), terms)
    }

